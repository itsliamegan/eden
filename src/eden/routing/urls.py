from collections.abc import Sequence
from dataclasses import dataclass

from helios.url import Pattern, URL

from ..content import Item
from .error import RouteError, RouteNotFoundError
from .route import PerItemExpansion, Route, SingleExpansion


@dataclass(init=False)
class URLs:
	"""A URL builder for routes, items, and paths under a base URL.

	URLs for named routes can be generated by their name. URLs for unnamed
	routes can be generated by the items they render or by their path.
	"""

	routes: list[Route]
	names: dict[str, Route]
	base_url: URL
	prefix: Pattern

	def __init__(self, routes: Sequence[Route], base_url: URL):
		if base_url.scheme is None or base_url.host is None:
			raise ValueError("base URL must be absolute")

		self.routes = list(routes)
		self.names = {}
		for route in routes:
			if route.name is not None:
				self.names[route.name] = route
		self.base_url = base_url
		self.prefix = Pattern.parse(base_url.path)

	def route(self, name: str, item: Item | None = None, absolute: bool = False) -> URL:
		route = self.names.get(name)
		if route is None:
			raise RouteNotFoundError(f"route not found: {name}")

		match route.expansion:
			case PerItemExpansion(collection=collection):
				if item is None:
					raise RouteError(f"route needs an item: {name}")
				if item.path.parent != collection:
					raise RouteError(f"item not in route's collection: {item.path}")
				path = route.path.path({"name": item.name})
			case SingleExpansion():
				if item is not None:
					raise RouteError(f"route takes no item: {name}")
				path = route.path.path()
		return self.path(path, absolute)

	def item(self, item: Item, absolute: bool = False) -> URL:
		for route in self.routes:
			match route.expansion:
				case PerItemExpansion(collection=collection):
					if item.path.parent == collection:
						return self.path(route.path.path({"name": item.name}), absolute)
				case SingleExpansion(item=path):
					if item.path == path:
						return self.path(route.path.path(), absolute)

		raise RouteNotFoundError(f"no route renders item: {item.path}")

	def path(self, path: str, absolute: bool = False) -> URL:
		path = Pattern.parse(path).prefixed(self.prefix).path()
		if absolute:
			return URL(
				path,
				scheme=self.base_url.scheme,
				host=self.base_url.host,
				port=self.base_url.port,
			)
		else:
			return URL(path)
